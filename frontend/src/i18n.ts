export const LanguageContext = createContext<{ lang: Lang; toggle: () => void }>({
  lang: "en",
  toggle: () => {},
});

export function useLanguage() {
  const { lang, toggle } = useContext(LanguageContext);
  return { lang, toggle, t: STRINGS[lang] };
}
