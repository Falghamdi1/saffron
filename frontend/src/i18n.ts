import { createContext, useContext } from "react";

export type Lang = "en" | "ar";
const STORED = "saffron.language";

export function initialLanguage(): Lang {
  try {
    const stored = localStorage.getItem(STORED);
    if (stored === "en" || stored === "ar") return stored;
  } catch {
    // Storage can be blocked; fall through to the browser's language.
  }
  return navigator.language.startsWith("ar") ? "ar" : "en";
}

/** The language on screen now, for code outside React. */
export const currentLanguage = (): Lang => (document.documentElement.lang === "ar" ? "ar" : "en");

export function applyLanguage(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  try {
    localStorage.setItem(STORED, lang);
  } catch {
    // The choice then lasts for this visit only.
  }
}

